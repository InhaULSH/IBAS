# 2 - 3. 인과관계 다이어그램과 교란 해소
# 상관관계는 인과관계가 아니므로 교란변수에 의해 두 관심변수간 회귀 계수가 편향 될 수 있음 따라서 기준에 따라서 회귀 분석에 사용할 변수를 선
# 택하는 것이 중요, 본격적으로 기준을 적용하기 전에 다이어그램을 여러 개의 개념적 단위로 분리하여 단위별로 기준을 적용하면 더 이해하기 용이함

# 분리 인과 기준 : 관심 변수 사이의 매개 변수를 제외하고 두 관심 변수 중 하나 이상의 변수에 직접적인 요인이 되는 변수를 회귀 분석 대상 변수
# 로 선택, 예를 들어 아래와 같은 다이어 그램에서 변수5와 변수4가 관심 변수라고 하면 변수1 및 변수3을 선택하면 교란은 해소된다. 따라서 다이
# 어그램에 오류가 다소 있더라도 교란 해소가 가능한 반면 불필요한 변수도 선택하게 될 수 있으므로중복에 가능성이 있고 더 많은 데이터를 필요로
# 하는 단점이 있다.
# 변수1 --> 변수 2 --> 변수3
#   |                  |
#   |                  v
#   ---> "변수5" ---> "변수4"

# 백도어 기준 : 관심 변수를 향하는 비인과적 경로(하나 이상의 충돌 또는 분기를 포함하는 경로)가 두 관심 변수 사이에 하나라도 있으면 두 변수간
# 인과관계가 교란된다. 이때 교란을 해소하려면 모든 비인과적 경로를 차단(경로상의 중간변수 중 하나를 회귀 분석 대상 변수로 선택하거나, 중심 변
# 수가 회귀 분석 대상 변수로 포함되지 않은 충돌이 존재함) 해야한다. 이때 경로란 두 변수간 화살표로 이어져있되 각 변수가 한번만 등장하는 경우
# 만을 말하며 특정 변수가 두 번이상 나오는 것은 경로가 아니다. 백도어 기준은 더 정교하며 명확하고 효율적으로 교란 요소를 분별할 수 있으나,
# 다이어그램상의 모든 관계가 정확해야하므로 인과관계 다이어그램의 오류에 취약하고 강건성이 부족하다.
