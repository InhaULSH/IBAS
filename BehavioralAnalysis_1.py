# 데이터 및 변수간의 관계를 나타낸 것, 화살표를 통해 인과관계를 표시하며 '변수1 -> 변수2' 로 표시할 경우 변수1은 변수2의 요인이라고 함
# 이때 화살표는 증가 또는 감소하는 상관관계의 방향이 아니며 변수간 원인과 결과를 나타내는 인과관계의 방향을 의미함, 관찰되지 않는 변수는
# 어둡게 표시하며, 변수를 그 구성요소별로 '분해' 하거나 직간접적인 관계가 동일한 변수끼리 '집계' 할 수 있음

# '변수1 -> 변수2 -> 변수3'
# 다이어그램 상에서 여러 변수간의 화살표가 한 방향으로만 연결된 형태를 '사슬' 이라고함, 이때 부모/자식 또는 조상/자손 관계가 성립함
# 사슬 상의 변수 일부를 제거하여 '축소' 할 수 있고 이때 관심있는 관계에 보다 초점을 맞출 수 있음, 사슬 상의 변수를 추가하여 '확장'
# 할 수 있고 이때 매개변수를 통해 현재 상황에서 무슨 일이 일어지고 있는 지에 대한 잠재적 이유를 더 자세히 이해할 수 있음
#        -> 변수3'
# '변수1 -
#        -> 변수2'
# 다이어그램상에서 여러 변수에 하나의 공통된 요인이 있는 형태를 '분기' 라고함, 이때 변수2와 변수3은 상관관계는 있으나 인과관계는 없고
# 변수1의 변동에 따라 같이 변동할 뿐임, 따라서 두 변수간 인과관계가 없는데 상관관계가 관측된다면 분기 형태로 다이어그램을 작성함이 적절,
# 주로 인구통계적 변수나 환경 변수가 변수1에 해당함, 이때 공통요인을 모르더라도 분기를 표시하고 싶을때는 두 변수간 양방향 화살표로 표시
# '변수1 -
#        -> 변수3'
# '변수2 -
# 다이어그램상에서 여러 변수가 동일한 변수에 영향을 미치는 형태를 '충돌' 이라고함
# '변수1 ->      -> 변수3'
#       <- 변수2 <-
# 다이어그램 상에서 변수들이 서로에게 인과적으로 영향을 미치는 형태를 '순환' 이라고함, 제품간의 '대체 효과' 나 환경에 변화에 따라 사람이
